#!/usr/bin/env python3
"""Build results/summary.md from the per-function JSON files written by sweep.py."""
import csv
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "results"
ORDER = ["exp", "exp2", "expm1", "log", "log2", "log10", "log1p", "sin", "cos", "tan",
         "arcsin", "arccos", "arctan", "sinh", "cosh", "tanh", "arcsinh", "arccosh",
         "arctanh", "cbrt", "sqrt"]


def numpy_test_tolerance(name, dtype):
    """ULP tolerance NumPy's own test-suite uses for this function (its bundled CSV), or None."""
    p = Path(np.__file__).parent / "_core/tests/data" / f"umath-validation-set-{name}.csv"
    if not p.exists():
        return None
    tol = None
    with open(p) as fh:
        for row in csv.reader(r for r in fh if r[0] not in "$#"):
            if row and row[0] == f"np.{dtype}":
                tol = max(tol or 0, int(row[3]))
    return tol


def main():
    out = ["# Results summary", "",
           "Generated by `src/report.py` from the JSON files in this folder. Do not edit by hand.", ""]
    for dtype in ("float32", "float16"):
        rows = []
        for name in ORDER:
            p = RES / f"{dtype}_{name}.json"
            if p.exists():
                rows.append(json.loads(p.read_text()))
        if not rows:
            continue
        out += [f"## {dtype} ({rows[0]['inputs']:,} inputs per function, NumPy {rows[0]['numpy']})", "",
                "| function | max error (ULP) | worst input (hex) | not correctly rounded | % of non-NaN | >1 ULP | >2 ULP | NumPy test tolerance (ULP) | monotonicity violations | \\|y\\|>1 |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            w = max(r["worst"], key=lambda z: z["err_ulp_mpmath"]) if r["worst"] else None
            tol = numpy_test_tolerance(r["function"], dtype)
            mono = r["mono_viol"] if r["mono_checked"] else "n/a"
            out.append("| {f} | {e:.4f} | {x} | {m:,} | {pc:.3f} | {g1:,} | {g2:,} | {tol} | {mono} | {gt1} |".format(
                f=r["function"], e=r["max_err_ulp"], x=w["x_hex"] if w else "-",
                m=r["misrounded"], pc=100 * r["misrounded"] / max(r["n_valid"], 1),
                g1=r["hist_err_gt"][1], g2=r["hist_err_gt"][3],
                tol=tol if tol is not None else "none", mono=mono, gt1=r.get("abs_gt_1", "n/a")))
        out += ["", "### Special values and layout dependence", "",
                "Counts of inputs. `layout_*` = result differs from the contiguous whole-array result.",
                "",
                "| function | NaN mismatch | zero-sign mismatch | inf mismatch | stride 2 | offset 1 | rows of 3 | reversed |",
                "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            out.append("| {function} | {nan_mismatch} | {zero_sign_mismatch} | {inf_mismatch} | {layout_stride2:,} | {layout_offset1:,} | {layout_len3:,} | {layout_reversed:,} |".format(**r))
        out += ["", "### Reference construction", "",
                "| function | hard cases sent to mpmath | of which rounding of float64 ref changed | max disagreement of the two float64 references (float64 ULP) | NaN/inf disagreement between references | seconds |",
                "|---|---|---|---|---|---|"]
        for r in rows:
            out.append("| {function} | {hard:,} | {hard_changed:,} | {ref_max_ulp64:.3g} | {ref_nan_disagree}/{ref_inf_disagree} | {seconds} |".format(**r))
        out.append("")
    (RES / "summary.md").write_text("\n".join(out))
    print("\n".join(out))


if __name__ == "__main__":
    main()
