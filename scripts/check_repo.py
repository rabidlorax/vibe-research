#!/usr/bin/env python3
"""Validate project READMEs and (with --write-index) regenerate PROJECTS.md.

Checks front matter fields and values, required sections, and that results are
not presented without the sections that keep them honest.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATUS = ["proposed", "active", "result", "verified", "refuted", "inconclusive", "abandoned"]
EVIDENCE = ["proved-formal", "proved-informal", "computed", "external-data", "literature", "conjecture"]
NOVELTY = ["unchecked", "searched-none-found", "known", "partially-known"]
FIELDS = ["title", "domain", "status", "evidence", "novelty", "models", "started", "updated"]
SECTIONS = [
    "Question", "Summary of result", "Claims", "Method", "Reproduction",
    "External data and what we could not reproduce", "Prior work and novelty",
    "Limitations and open questions", "Review log",
]
# Once a project reports a result, these sections must have real content.
MUST_FILL = ["Summary of result", "Reproduction", "External data and what we could not reproduce",
             "Limitations and open questions"]
# Links to files in the math repository must be pinned to a full commit hash.
MATH_LINK = re.compile(r"https://github\.com/rabidlorax/math/(?:blob|tree|blame|raw)/[^\s)>\]]*", re.I)
MATH_PERMALINK = re.compile(r"https://github\.com/rabidlorax/math/blob/[0-9a-f]{40}/\S+", re.I)
REPORTING = {"result", "verified", "refuted", "inconclusive"}


def parse(path):
    text = path.read_text()
    m = re.match(r"---\n(.*?)\n---\n(.*)", text, re.S)
    if not m:
        return None, text
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, m.group(2)


def sections(body):
    parts = re.split(r"^## +(.+?)\s*$", body, flags=re.M)
    return {parts[i]: parts[i + 1].strip() for i in range(1, len(parts) - 1, 2)}


def check(path, template_sections):
    errors = []
    meta, body = parse(path)
    domain = path.parts[-4]
    if meta is None:
        return ["missing front matter"], {}
    for f in FIELDS:
        if f not in meta:
            errors.append(f"front matter missing '{f}'")
    for key, allowed in (("status", STATUS), ("evidence", EVIDENCE), ("novelty", NOVELTY)):
        if key in meta and meta[key] not in allowed:
            errors.append(f"{key} '{meta[key]}' not one of {allowed}")
    if meta.get("domain") != domain:
        errors.append(f"domain '{meta.get('domain')}' does not match directory '{domain}'")
    secs = sections(body)
    for s in SECTIONS:
        if s not in secs:
            errors.append(f"missing section '## {s}'")
    for link in MATH_LINK.findall(body):
        if not MATH_PERMALINK.fullmatch(link):
            errors.append(f"link into the math repository is not a permalink at a full commit hash: {link}")
    status = meta.get("status")
    if status in REPORTING:
        for s in MUST_FILL:
            if s in secs and (not secs[s] or secs[s] == template_sections.get(s)):
                errors.append(f"status is '{status}' but section '## {s}' is still the template text")
        if meta.get("models") in ("[]", "", None):
            errors.append(f"status is '{status}' but 'models' is empty")
    if status == "verified":
        rows = [l for l in secs.get("Review log", "").splitlines() if l.startswith("|")]
        if len(rows) < 3:
            errors.append("status is 'verified' but the review log has no entries")
    return errors, meta


def main():
    template_sections = sections(parse(ROOT / "templates" / "project-README.md")[1])
    failed = False
    rows = []
    for d in sorted((ROOT / "domains").iterdir()):
        if not d.is_dir():
            continue
        if not (d / "README.md").is_file():
            print(f"{d.relative_to(ROOT)}: missing README.md")
            failed = True
        for p in sorted((d / "projects").glob("*/")):
            readme = p / "README.md"
            if not readme.is_file():
                print(f"{p.relative_to(ROOT)}: missing README.md")
                failed = True
                continue
            errors, meta = check(readme, template_sections)
            for e in errors:
                print(f"{readme.relative_to(ROOT)}: {e}")
            failed = failed or bool(errors)
            rows.append((d.name, p.name, meta))
    lines = [
        "# Project index", "",
        "Generated by `python scripts/check_repo.py --write-index`. Do not edit by hand.", "",
    ]
    if rows:
        lines += ["| Domain | Project | Status | Evidence | Novelty | Updated |", "|---|---|---|---|---|---|"]
        for domain, slug, m in rows:
            link = f"[{m.get('title', slug)}](domains/{domain}/projects/{slug}/)"
            lines.append(f"| {domain} | {link} | {m.get('status','?')} | {m.get('evidence','?')} "
                         f"| {m.get('novelty','?')} | {m.get('updated','?')} |")
    else:
        lines.append("No projects yet.")
    index = "\n".join(lines) + "\n"
    target = ROOT / "PROJECTS.md"
    if "--write-index" in sys.argv:
        target.write_text(index)
    elif not target.is_file() or target.read_text() != index:
        print("PROJECTS.md is out of date; run python scripts/check_repo.py --write-index")
        failed = True
    print(f"{len(rows)} project(s) checked: {'FAILED' if failed else 'ok'}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
